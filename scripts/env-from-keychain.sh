#!/usr/bin/env bash
# Write $ENV_OUT (default .env) from macOS keychain generic-password items.
# Usage: ./scripts/env-from-keychain.sh [--force]
#
#   KEYCHAIN_SPLUNK_SERVICE      (S4R-demo)    password for both admin and splunker
#   KEYCHAIN_SPLUNKBASE_SERVICE  (splunkbase)  account = Splunkbase user, password = Splunkbase password
#
# Store them once (prompts for the password, keeps it out of shell history):
#   security add-generic-password -s S4R-demo -a "$USER" -U -w
#   security add-generic-password -s splunkbase -a <splunkbase-user> -U -w
#
# An existing $ENV_OUT is kept unless --force. Values are never printed.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

ENV_OUT="${ENV_OUT:-.env}"
SPLUNK_SERVICE="${KEYCHAIN_SPLUNK_SERVICE:-S4R-demo}"
SPLUNKBASE_SERVICE="${KEYCHAIN_SPLUNKBASE_SERVICE:-splunkbase}"

force=0
case "${1:-}" in
  "") ;;
  --force) force=1 ;;
  -h|--help)
    sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    echo "Usage: $(basename "$0") [--force]" >&2
    exit 1
    ;;
esac

if ! command -v security >/dev/null 2>&1; then
  echo "Error: macOS 'security' not found; export the secrets or write ${ENV_OUT} by hand (see .env.example)." >&2
  exit 1
fi

if [[ -f "$ENV_OUT" && "$force" != 1 ]]; then
  echo "${ENV_OUT} already exists; use --force to overwrite it from the keychain." >&2
  exit 1
fi

keychain_password() { # $1 = service
  security find-generic-password -s "$1" -w 2>/dev/null || {
    echo "Error: keychain item '$1' not found (security add-generic-password -s $1 -a <account> -U -w)." >&2
    return 1
  }
}

keychain_account() { # $1 = service
  security find-generic-password -s "$1" 2>/dev/null | sed -n 's/^ *"acct"<blob>="\(.*\)"$/\1/p'
}

# Single quotes keep values literal for both bash (with-splunk-env.sh) and Compose.
check_quotable() { # $1 = name, $2 = value
  case "$2" in
    "") echo "Error: $1 is empty in the keychain." >&2; return 1 ;;
    *"'"*|*$'\n'*) echo "Error: $1 contains a single quote or newline; write ${ENV_OUT} by hand." >&2; return 1 ;;
  esac
}

splunk_pw="$(keychain_password "$SPLUNK_SERVICE")"
splunkbase_pass="$(keychain_password "$SPLUNKBASE_SERVICE")"
splunkbase_user="$(keychain_account "$SPLUNKBASE_SERVICE")"
check_quotable "${SPLUNK_SERVICE} password" "$splunk_pw"
check_quotable "${SPLUNKBASE_SERVICE} password" "$splunkbase_pass"
check_quotable "${SPLUNKBASE_SERVICE} account" "$splunkbase_user"

tmp="$(umask 077 && mktemp "${ENV_OUT}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
cat >"$tmp" <<EOF
# Generated by scripts/env-from-keychain.sh from keychain items
# '${SPLUNK_SERVICE}' and '${SPLUNKBASE_SERVICE}'. Never commit this file.
SPLUNK_ADMIN_PASSWORD='${splunk_pw}'
SPLUNKBASE_USER='${splunkbase_user}'
SPLUNKBASE_PASS='${splunkbase_pass}'
SPLUNK_SPLUNKER_PASSWORD='${splunk_pw}'
EOF
chmod 600 "$tmp"
mv "$tmp" "$ENV_OUT"
trap - EXIT
echo "Wrote ${ENV_OUT} from keychain items '${SPLUNK_SERVICE}' and '${SPLUNKBASE_SERVICE}'."
